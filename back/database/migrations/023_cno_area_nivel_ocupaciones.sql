-- ============================================================
--  023_cno_area_nivel_ocupaciones
--
--  591 de las 612 ocupaciones CNO estaban con área 1 / nivel 1 en la BD,
--  aunque el catálogo oficial "CNO_2026_Actualizado.xlsx" las reparte en
--  10 áreas y 6 niveles. Por eso la consulta y la API pública mostraban
--  "Finanzas y Administración" para casi todo (p. ej. 2111 Físicos).
--
--  Causa: el cargue actualizaba el TEXTO del área/nivel de una ocupación
--  existente pero nunca la RELACIÓN (cod_desempeno_cno/cod_cualificacion_cno),
--  así que las que llegaron mal en una carga antigua no se corregían.
--  Corregido en cno-bulk-upload.service.ts.
--
--  Además la hoja "nivel_cualificacion" del libro oficial trae nombres de
--  ÁREAS en la columna del nombre del nivel. Los nombres correctos salen de
--  las descripciones oficiales ("Nivel 1 (A)", "Nivel 2 (B)"...) y de la
--  columna de nivel de la hoja Ocupaciones. Los niveles 5, 7, 8 y 9 no los
--  usa ninguna ocupación: eran filas de áreas copiadas y se eliminan.
--
--  Qué hace:
--    1. Nombres correctos de los niveles 0, 1, 2, 3, 4 y 6.
--    2. Área y nivel de cada ocupación según el catálogo oficial.
--    3. Resincroniza las columnas de texto nom_desempeno / niveles_cualificacion.
--    4. Elimina los niveles sin uso (5, 7, 8, 9), solo si nada los referencia.
--
--  Idempotente. Sin BEGIN/COMMIT: el runner envuelve el archivo.
-- ============================================================

UPDATE clasificacion.cno_nivel_cualificacion n
SET niveles_cualificacion = v.nombre
FROM (VALUES
  ('0', 'Dirección y Gerencia'),
  ('1', 'Nivel 1 (A) - Profesionales'),
  ('2', 'Nivel 2 (B) - Técnicos y supervisores'),
  ('3', 'Nivel 3 (C) - Auxiliares y operativos'),
  ('4', 'Nivel 4 (C) - Auxiliares y operativos'),
  ('6', 'Nivel 6 (D) - Obreros y ayudantes')
) AS v(cod, nombre)
WHERE n.cod_cualificacion = v.cod
  AND n.niveles_cualificacion IS DISTINCT FROM v.nombre;

