--  012_habilidades_cno_carga
--
--  Carga las habilidades por ocupación CNO desde el catálogo oficial
--  "2CNO_2024_(2025-06-13).xlsx", hoja «Habilidades - C.N.O.».
--
--  Por qué: `cno_reg_habilidad` tenía 42 filas para 620 ocupaciones — solo 10
--  ocupaciones con alguna habilidad. Ni siquiera la ocupación original (sin
--  copiar) las tenía, así que Comparativa y Validación Experta mostraban
--  "Sin habilidades registradas" para casi todo. La tabla catálogo
--  `habilidad_destreza` sí estaba completa (códigos 1-40); lo que faltaba
--  era el vínculo ocupación→habilidad.
--
--  Dos pasos:
--    1. Originales: se insertan los pares (ocupación, habilidad) del Excel.
--    2. Copias de análisis ya existentes: se les propagan las habilidades de
--       su ocupación base (la copia se creó cuando el original no tenía
--       ninguna, así que heredó el vacío). La base se obtiene quitando el
--       sufijo derivado del código; solo aplica a filas marcadas como copia
--       (`id_comparativa IS NOT NULL`, migraciones 008/011).
--
--  Idempotente en ambos pasos: no inserta un par (ocupación, habilidad) que ya
--  exista. Las FK a `cno_ocupacion` y `habilidad_destreza` se respetan porque
--  solo se insertan ocupaciones y códigos presentes en esas tablas.
--
--  NO lleva BEGIN/COMMIT: el runner envuelve cada archivo en su transacción.
-- ============================================================

