INSERT INTO clasificacion.cno_reg_habilidad (cod_ocupacion_cno, codigo_habilidad, nomb_hab_dest)
SELECT t.cod_ocupacion, t.cod_hab, t.nombre
FROM   tmp_hab_cno t
JOIN   clasificacion.cno_ocupacion o      ON o.cod_ocupacion_cno = t.cod_ocupacion
JOIN   clasificacion.habilidad_destreza h ON h.cod_hab_dest = t.cod_hab
WHERE  NOT EXISTS (
         SELECT 1 FROM clasificacion.cno_reg_habilidad r
         WHERE  r.cod_ocupacion_cno = t.cod_ocupacion AND r.codigo_habilidad = t.cod_hab
       );

-- 2. Copias existentes: heredan de su ocupación base
INSERT INTO clasificacion.cno_reg_habilidad (cod_ocupacion_cno, codigo_habilidad, nomb_hab_dest)
SELECT copia.cod_ocupacion_cno, t.cod_hab, t.nombre
FROM   clasificacion.cno_ocupacion copia
JOIN   tmp_hab_cno t ON t.cod_ocupacion = regexp_replace(copia.cod_ocupacion_cno, '-[0-9]+(-[0-9]+)?$', '')
JOIN   clasificacion.habilidad_destreza h ON h.cod_hab_dest = t.cod_hab
WHERE  copia.id_comparativa IS NOT NULL
  AND  NOT EXISTS (
         SELECT 1 FROM clasificacion.cno_reg_habilidad r
         WHERE  r.cod_ocupacion_cno = copia.cod_ocupacion_cno AND r.codigo_habilidad = t.cod_hab
       );
