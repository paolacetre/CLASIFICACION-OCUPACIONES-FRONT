-- ============================================================================
-- 029 · La validación experta pasa a `respuestas` + `pregunta_respuesta`
-- ============================================================================
--
-- `validacion_experta` y `validacion_experta_campo` (migración 004) eran una
-- copia de `respuestas` y `pregunta_respuesta`, que son las tablas originales
-- del esquema. Aquí las originales reciben lo que les faltaba y se copian los
-- veredictos ya guardados; la 030 borra las dos tablas sobrantes.
--
-- Además el modelo pasa de UN experto por instrumento a VARIOS (unos 11):
--   · `respuestas`: una fila por experto, instrumento y ronda.
--   · `pregunta.ronda`: el snapshot se congela al enviarlo a expertos. Si el
--     analista lo reenvía tras ajustes, se escribe una ronda nueva en vez de
--     borrar la que ya tiene respuestas.
--   · `instrumento_experto`: a quién se le asignó cada instrumento y ronda.
--
-- Columnas que NO pasan: `experto_nombre` (sale de `usuario` por idusuario),
-- `razon` y `etiqueta` (sin uso), `valor_original` y `cod_ocupacion` del
-- veredicto (salen de `pregunta` por la FK). `observacion` y
-- `propuesta_mejora` se unen en `pregunta_respuesta.otro`: el formulario solo
-- tiene un comentario por criterio y `respuesta` ya dice de qué tipo es.
--
-- Idempotente. Sin BEGIN/COMMIT: el runner envuelve el archivo.
-- ============================================================================

SET search_path TO clasificacion;

-- `respuestas` solo la escribe la validación experta. Una fila previa no
-- tendría instrumento y no se puede adivinar cuál: mejor abortar que inventar.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'clasificacion' AND table_name = 'respuestas'
      AND column_name = 'id_instrumento'
  ) THEN
    RETURN;
  END IF;
  IF EXISTS (SELECT 1 FROM clasificacion.respuestas) THEN
    RAISE EXCEPTION 'respuestas tiene filas sin instrumento: revísalas antes de aplicar 029';
  END IF;
END $$;

-- ── 1. respuestas: cabecera, una por experto, instrumento y ronda ──────────

ALTER TABLE clasificacion.respuestas
  ADD COLUMN IF NOT EXISTS id_instrumento   INTEGER     NULL,
  -- en_revision | aprobada | rechazada | ajustes_solicitados
  ADD COLUMN IF NOT EXISTS estado           VARCHAR(40) NULL,
  ADD COLUMN IF NOT EXISTS observaciones    TEXT        NULL,
  ADD COLUMN IF NOT EXISTS fecha_validacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  ADD COLUMN IF NOT EXISTS ronda            INTEGER     NOT NULL DEFAULT 1;

-- Opcionales en BD: el experto guarda avances antes de diligenciar sus datos
-- y el cierre ya los exige por código. `sector` no tiene filas todavía y el
-- formulario de Instrumento 2 no lo pide.
ALTER TABLE clasificacion.respuestas
  ALTER COLUMN departamento  DROP NOT NULL,
  ALTER COLUMN municipio     DROP NOT NULL,
  ALTER COLUMN sector_codigo DROP NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_respuestas_instrumento') THEN
    ALTER TABLE clasificacion.respuestas
      ADD CONSTRAINT fk_respuestas_instrumento
      FOREIGN KEY (id_instrumento) REFERENCES clasificacion.instrumento (idinstrumento)
      ON DELETE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_respuestas_instrumento_usuario_ronda') THEN
    ALTER TABLE clasificacion.respuestas
      ADD CONSTRAINT uq_respuestas_instrumento_usuario_ronda UNIQUE (id_instrumento, idusuario, ronda);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_respuestas_estado') THEN
    ALTER TABLE clasificacion.respuestas
      ADD CONSTRAINT ck_respuestas_estado
      CHECK (estado IN ('en_revision', 'aprobada', 'rechazada', 'ajustes_solicitados'));
  END IF;
END $$;

-- ── 2. pregunta: ronda del snapshot ────────────────────────────────────────

ALTER TABLE clasificacion.pregunta
  ADD COLUMN IF NOT EXISTS ronda INTEGER NOT NULL DEFAULT 1;

CREATE INDEX IF NOT EXISTS ix_pregunta_instrumento_ronda
  ON clasificacion.pregunta (id_instrumento, ronda);

-- ── 3. pregunta_respuesta: veredicto por ítem ──────────────────────────────

-- `id` sin autoincremento obligaba a inventar el número al insertar; con
-- varios expertos guardando a la vez dos podían elegir el mismo.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'clasificacion' AND table_name = 'pregunta_respuesta'
      AND column_name = 'id' AND is_identity = 'YES'
  ) THEN
    ALTER TABLE clasificacion.pregunta_respuesta
      ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    PERFORM setval(
      pg_get_serial_sequence('clasificacion.pregunta_respuesta', 'id'),
      COALESCE((SELECT MAX(id) FROM clasificacion.pregunta_respuesta), 0) + 1,
      false
    );
  END IF;
END $$;

-- Texto que el experto propone para el ítem (descripción y área de
-- desempeño). Antes reescribía directamente la ocupación; con varios expertos
-- se pisaban entre sí. Ahora queda como propuesta y el analista decide.
ALTER TABLE clasificacion.pregunta_respuesta
  ADD COLUMN IF NOT EXISTS valor_propuesto TEXT NULL;

DO $$
BEGIN
  -- Borrar la cabecera borra sus renglones.
  IF EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'fk_pregunta_respuesta_respuestas' AND confdeltype <> 'c'
  ) THEN
    ALTER TABLE clasificacion.pregunta_respuesta DROP CONSTRAINT fk_pregunta_respuesta_respuestas;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_pregunta_respuesta_respuestas') THEN
    ALTER TABLE clasificacion.pregunta_respuesta
      ADD CONSTRAINT fk_pregunta_respuesta_respuestas
      FOREIGN KEY (idrespuesta) REFERENCES clasificacion.respuestas (idrespuesta)
      ON DELETE CASCADE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_pregunta_respuesta_respuesta_pregunta') THEN
    ALTER TABLE clasificacion.pregunta_respuesta
      ADD CONSTRAINT uq_pregunta_respuesta_respuesta_pregunta UNIQUE (idrespuesta, id_pregunta);
  END IF;
  -- Lista cerrada: es lo que permite contar y agrupar las respuestas.
  -- NULL = el experto editó el texto del ítem pero aún no lo calificó.
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_pregunta_respuesta_respuesta') THEN
    ALTER TABLE clasificacion.pregunta_respuesta
      ADD CONSTRAINT ck_pregunta_respuesta_respuesta
      CHECK (respuesta IN ('aplica', 'no_aplica', 'requiere_ajuste', 'propuesta_mejora'));
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_pregunta_respuesta_pregunta
  ON clasificacion.pregunta_respuesta (id_pregunta);

-- ── 4. instrumento_experto: expertos asignados ─────────────────────────────

CREATE TABLE IF NOT EXISTS clasificacion.instrumento_experto (
  id               INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_instrumento   INTEGER     NOT NULL,
  idusuario        INTEGER     NOT NULL,
  ronda            INTEGER     NOT NULL DEFAULT 1,
  asignado_por     INTEGER     NULL,
  fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT fk_instrumento_experto_instrumento
    FOREIGN KEY (id_instrumento) REFERENCES clasificacion.instrumento (idinstrumento)
    ON DELETE CASCADE,
  CONSTRAINT fk_instrumento_experto_usuario
    FOREIGN KEY (idusuario) REFERENCES clasificacion.usuario (idusuario),
  CONSTRAINT fk_instrumento_experto_asignado_por
    FOREIGN KEY (asignado_por) REFERENCES clasificacion.usuario (idusuario),
  CONSTRAINT uq_instrumento_experto UNIQUE (id_instrumento, idusuario, ronda)
);

-- ── 5. Copia de los veredictos de validacion_experta ───────────────────────
--
-- El criterio se enlaza a su fila de `pregunta` con la misma regla del
-- código (`campos-validables.ts`): por ocupación, un identificador único va
-- tal cual ("nombre") y uno repetido se numera por orden ("funcion_2").
-- Un criterio sin fila no se puede enlazar: se aborta en vez de perderlo.

DO $$
DECLARE
  v RECORD;
  nueva_id INTEGER;
  copiados INTEGER;
  esperados INTEGER;
BEGIN
  IF to_regclass('clasificacion.validacion_experta') IS NULL THEN
    RETURN;
  END IF;

  IF EXISTS (SELECT 1 FROM clasificacion.validacion_experta WHERE idusuario IS NULL) THEN
    RAISE EXCEPTION 'validacion_experta tiene veredictos sin usuario: asígnalos antes de aplicar 029';
  END IF;

  FOR v IN
    SELECT ve.*, i.ocupacion AS principal
    FROM clasificacion.validacion_experta ve
    JOIN clasificacion.instrumento i ON i.idinstrumento = ve.id_instrumento
    WHERE NOT EXISTS (
      SELECT 1 FROM clasificacion.respuestas r
      WHERE r.id_instrumento = ve.id_instrumento AND r.idusuario = ve.idusuario AND r.ronda = 1
    )
    ORDER BY ve.id_validacion
  LOOP
    INSERT INTO clasificacion.respuestas (
      idusuario, id_instrumento, estado, observaciones, fecha_validacion, ronda,
      nombre_apellido, email, telefono, departamento, municipio,
      empresa_entidad, cargo, "profesión"
    ) VALUES (
      v.idusuario, v.id_instrumento, v.estado, v.observaciones, v.fecha_validacion, 1,
      NULLIF(concat_ws(' ', NULLIF(trim(v.informante_nombre), ''), NULLIF(trim(v.informante_apellido), '')), ''),
      v.informante_email, v.informante_telefono, v.informante_departamento, v.informante_municipio,
      v.informante_empresa, v.informante_cargo, v.informante_profesion
    )
    RETURNING idrespuesta INTO nueva_id;

    WITH p AS (
      SELECT p.id_pregunta, p.identificador,
             COALESCE(NULLIF(trim(p.cod_ocupacion), ''), trim(v.principal)) AS ocupacion,
             row_number() OVER w AS n,
             count(*) OVER (PARTITION BY COALESCE(NULLIF(trim(p.cod_ocupacion), ''), trim(v.principal)), p.identificador) AS total
      FROM clasificacion.pregunta p
      WHERE p.id_instrumento = v.id_instrumento
      WINDOW w AS (
        PARTITION BY COALESCE(NULLIF(trim(p.cod_ocupacion), ''), trim(v.principal)), p.identificador
        ORDER BY p.id_pregunta
      )
    ), campos AS (
      SELECT id_pregunta, ocupacion,
             CASE WHEN total > 1 THEN identificador || '_' || n ELSE identificador END AS campo
      FROM p
    )
    INSERT INTO clasificacion.pregunta_respuesta (idusuario, idrespuesta, id_pregunta, respuesta, otro)
    SELECT v.idusuario, nueva_id, campos.id_pregunta, c.estado,
           -- Mismo comentario que mostraba Resumen: la propuesta o, si no, la
           -- observación; un código de motivo repetido no es comentario.
           NULLIF(
             CASE
               WHEN COALESCE(NULLIF(trim(c.propuesta_mejora), ''), NULLIF(trim(c.observacion), '')) = c.razon THEN NULL
               ELSE COALESCE(NULLIF(trim(c.propuesta_mejora), ''), NULLIF(trim(c.observacion), ''))
             END,
             ''
           )
    FROM clasificacion.validacion_experta_campo c
    JOIN campos
      ON campos.campo = c.campo
     AND campos.ocupacion = COALESCE(NULLIF(trim(c.cod_ocupacion), ''), trim(v.principal))
    WHERE c.id_validacion = v.id_validacion;

    GET DIAGNOSTICS copiados = ROW_COUNT;
    SELECT count(*) INTO esperados
    FROM clasificacion.validacion_experta_campo
    WHERE id_validacion = v.id_validacion;

    IF copiados <> esperados THEN
      RAISE EXCEPTION
        'Validación % (instrumento %): % de % criterios no se pudieron enlazar a su pregunta',
        v.id_validacion, v.id_instrumento, esperados - copiados, esperados;
    END IF;
  END LOOP;
END $$;

-- ── 6. Asignaciones de los instrumentos ya enviados ───────────────────────
--
-- Antes no se asignaba: todos los expertos veían todo. Para no esconderle a
-- nadie lo que ya tenía en su bandeja, cada instrumento enviado queda
-- asignado a quien ya respondió y, si sigue abierto, a todos los expertos
-- activos.

INSERT INTO clasificacion.instrumento_experto (id_instrumento, idusuario, ronda)
SELECT DISTINCT r.id_instrumento, r.idusuario, r.ronda
FROM clasificacion.respuestas r
JOIN clasificacion.usuario_roles ur ON ur.idusuario = r.idusuario
JOIN clasificacion.roles ro ON ro.id = ur.id_roles AND upper(ro.nombre) = 'EXPERTO'
WHERE r.id_instrumento IS NOT NULL
ON CONFLICT (id_instrumento, idusuario, ronda) DO NOTHING;

INSERT INTO clasificacion.instrumento_experto (id_instrumento, idusuario, ronda)
SELECT i.idinstrumento, u.idusuario, 1
FROM clasificacion.instrumento i
CROSS JOIN clasificacion.usuario u
JOIN clasificacion.usuario_roles ur ON ur.idusuario = u.idusuario
JOIN clasificacion.roles ro ON ro.id = ur.id_roles AND upper(ro.nombre) = 'EXPERTO'
WHERE i.estado = 'ENVIADO_EXPERTO'
  AND COALESCE(u.estado, 1) = 1
ON CONFLICT (id_instrumento, idusuario, ronda) DO NOTHING;

-- Con los datos ya copiados, el instrumento es obligatorio.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM clasificacion.respuestas WHERE id_instrumento IS NULL OR estado IS NULL) THEN
    RAISE EXCEPTION 'respuestas quedó con filas sin instrumento o sin estado';
  END IF;
END $$;

ALTER TABLE clasificacion.respuestas
  ALTER COLUMN id_instrumento SET NOT NULL,
  ALTER COLUMN estado SET NOT NULL;
